use polars::prelude::*;

/// Lista de indicadores:
/// ATR                  Average True Range
/// NATR                 Normalized Average True Range
/// TRANGE               True Range

pub async fn atr(df: DataFrame) -> PolarsResult<DataFrame> {
    Ok(df)
}

pub async fn natr(df: DataFrame) -> PolarsResult<DataFrame> {
    Ok(df)
}

pub async fn trange(df: DataFrame) -> PolarsResult<DataFrame> {
    Ok(df)
}
